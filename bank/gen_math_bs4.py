# ---------- 从 gen_math_bs5.py 复制的清理 helpers ----------
def _simplify_opt(o):
    """把 '6/1' -> '6'，'−6/1' -> '−6'；其它原样返回"""
    neg = False
    if o.startswith("−"):
        neg = True; o = o[1:]
    if "/" in o:
        a, b = o.split("/")
        if b == "1":
            o = a
    return ("−" if neg else "") + o

def fstr(f):
    """Fraction -> 字符串：分母为1时显示整数，否则 分子/分母"""
    if f.denominator == 1:
        return str(f.numerator)
    return "%d/%d" % (f.numerator, f.denominator)

def dstr(x, nd=4):
    """小数 -> 干净字符串：去掉多余的 0 与小数点（12.0 -> '12'，3.50 -> '3.5'，0.032 保留）"""
    x = round(x, nd)
    if x == 0:
        return "0"
    s = ("%.*f" % (nd, x)).rstrip("0").rstrip(".")
    if s in ("", "-"):
        return "0"
    return s

def rnd(a, b):
    return random.randint(a, b)

def mk(c, ch, q, correct, wrongs, k, e, d=0):
    correct = _simplify_opt(correct)
    wrongs = [_simplify_opt(w) for w in wrongs]
    wrongs = list(wrongs)
    # 保证干扰项与正确答案不同且去重
    wrongs = [w for w in wrongs if w != correct]
    seen = {correct}
    out = []
    for w in wrongs:
        if w not in seen:
            out.append(w); seen.add(w)
    # 不足 3 个时用中性填充
    fillers = ["以上都不对", "无法确定", "都有可能", "都有可能"]
    j = 0
    while len(out) < 3:
        f = fillers[j % len(fillers)]; j += 1
        if f not in seen:
            out.append(f); seen.add(f)
    opts = [correct] + out[:3]
    random.shuffle(opts)
    a = opts.index(correct)
    return {"c": c, "ch": ch, "f": 0, "d": d, "q": q, "o": opts, "a": a, "k": k, "e": e}

