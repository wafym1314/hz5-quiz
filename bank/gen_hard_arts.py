def js_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def gen(grade, subj, pool, per_chapter=8):
    key = '%d%s' % (grade, subj)
    chs = CH.get(key, {})
    lines = []
    idx = 9000
    for code in sorted(chs.keys()):
        title = chs[code]['ch']
        n = min(per_chapter, len(pool))
        picked = random.sample(pool, n)
        for (q, opts, ai, k, e) in picked:
            if len(set(opts)) != 4 or not (0 <= ai <= 3):
                continue
            lines.append('{i:%d,c:%s,ch:%s,f:0,d:2,q:%s,o:[%s],a:%d,k:%s,e:%s}' % (
                idx, js_str(code), js_str(title), js_str(q),
                ','.join(js_str(o) for o in opts), ai, js_str(k), js_str(e)))
            idx += 1
    if not lines:
        print('  %s: 无题' % key)
        return 0
    out = ('if(!global.QA)global.QA={};\nif(!QA["%s"])QA["%s"]=[];\nQA["%s"].push(\n%s\n);\n'
           % (key, key, key, ',\n'.join(lines)))
    path = os.path.join(BASE, 'new', 'g%d%s_hard.js' % (grade, subj))
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(out)
    print('  %s: %d 道拔高题（%d 章）→ %s' % (key, len(lines), len(chs), os.path.basename(path)))
    return len(lines)

