out = []
n_repl = n_relbl = 0.0
n_repl = n_relbl = 0
seen_repl, seen_relbl = set(), set()

for ln in lines:
    m = re.match(r'^\{i:(\d+),', ln)
    if not m:
        out.append(ln)
        continue
    i = int(m.group(1))
    if i in REPL:
        code, ch, q, a, k, e = REPL[i]
        out.append('{i:%d,c:"%s",ch:"%s",f:1,q:"%s",o:[],a:"%s",k:"%s",e:"解析：%s"},'
                   % (i, code, ch, q, a, k, e))
        n_repl += 1
        seen_repl.add(i)
        continue
    if i in RELBL:
        new_k = RELBL[i]
        ln2, cnt = re.subn(r'k:"[^"]*"', 'k:"%s"' % new_k, ln, count=1)
        assert cnt == 1, 'i=%d 没能替换 k' % i
        out.append(ln2)
        n_relbl += 1
        seen_relbl.add(i)
        continue
    out.append(ln)

missing_repl = sorted(set(REPL) - seen_repl)
missing_relbl = sorted(set(RELBL) - seen_relbl)
io.open(SRC, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))

