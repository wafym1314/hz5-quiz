from fractions import Fraction as F


def pct(x):
    """0.25 → '25%'"""
    v = x * 100 if x < 1 else x
    s = ('%.2f' % v).rstrip('0').rstrip('.')
    return s + '%'


def fpct(fr):
    """Fraction(1,4) → '25%'"""
    return pct(float(fr))


def num(x):
    if isinstance(x, F):
        if x.denominator == 1:
            return str(x.numerator)
        return '%d/%d' % (x.numerator, x.denominator)
    s = ('%.2f' % x).rstrip('0').rstrip('.')
    return s


