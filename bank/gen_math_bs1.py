def u_add100(c, ch):
    R=[]
    for _ in range(8):
        a=rnd(20,80); ao=a%10
        bo=rnd(0,9-ao)            # 个位相加 < 10 → 不进位
        b=rnd(1,8)*10+bo
        s=a+b
        R.append(mk(c,ch,"%d + %d = ?"%(a,b), str(s),
                    [str(s+10),str(s-10),str(s+1)],
                    "100以内不进位加法：个位加个位，十位加十位",
                    "解析：%d + %d = %d。"%(a,b,s)))
    for _ in range(8):
        a=rnd(40,95); ao=a%10
        bo=rnd(0,ao)              # 个位够减 → 不借位
        b=rnd(1,8)*10+bo
        while b>a: b-=10
        R.append(mk(c,ch,"%d − %d = ?"%(a,b), str(a-b),
                    [str(a-b+10),str(a+b),str(b)],
                    "100以内不退位减法",
                    "解析：%d − %d = %d。"%(a,b,a-b)))
    for _ in range(5):
        a=rnd(30,80); ao=a%10
        bo=rnd(0,ao)
        b=rnd(1,8)*10+bo
        while b>a: b-=10
        R.append(mk(c,ch,"小明有 %d 元，买书花了 %d 元，还剩（　）元。"%(a,b), str(a-b),
                    [str(a+b),str(a-b+10),str(b)],
                    "减法应用题",
                    "解析：%d − %d = %d 元。"%(a,b,a-b)))
    return R

