import random, json, math

random.seed(20260904)

def rnd(a,b): return random.randint(a,b)

def mk(c, ch, q, correct, *rest, d=0):
    # rest 可以是 [wrongs_list, k, e] 或 [w1, w2, w3, k, e]，末尾可带 d=2
    if rest and isinstance(rest[-1], int):
        d = rest[-1]; rest = rest[:-1]
    if len(rest) == 3 and isinstance(rest[0], list):
        wrongs = rest[0]; k = rest[1]; e = rest[2]
    else:
        wrongs = list(rest[:3]); k = rest[3]; e = rest[4]
    wrongs = list(wrongs)
    wrongs = [w for w in wrongs if w != correct]
    seen = {correct}; out = []
    for w in wrongs:
        if w not in seen:
            out.append(w); seen.add(w)
    fillers = ["以上都不对","无法确定","都有可能"]
    j = 0
    while len(out) < 3:
        f = fillers[j % len(fillers)]; j += 1
        if f not in seen:
            out.append(f); seen.add(f)
    opts = [correct] + out[:3]
    random.shuffle(opts)
    a = opts.index(correct)
    return {"c":c,"ch":ch,"f":0,"d":d,"q":q,"o":opts,"a":a,"k":k,"e":e}

