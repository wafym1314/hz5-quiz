    R.append(mk(c,ch,"60秒 = （　）分","1","60","100","10","60秒=1分","解析：60秒=1分。"))
    R.append(mk(c,ch,"小明每天睡觉约9（　）。","时","分","秒","天","时间单位选择","解析：睡觉时间用‘时’。"))
    R.append(mk(c,ch,"跑50米大约用10（　）。","秒","分","时","天","短用时用秒","解析：跑50米用秒。"))
