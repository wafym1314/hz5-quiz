def u_time(c, ch):  # 2sx-16 时、分、秒
    R=[]
    R.append(mk(c,ch,"1时 = （　）分","60","100","12","30","时与分：1时=60分","解析：1时=60分。"))
    R.append(mk(c,ch,"1分 = （　）秒","60","100","10","30","分与秒：1分=60秒","解析：1分=60秒。"))
