from fractions import Fraction as F

PI = 3.14


def num(x):
    """整数/小数转字符串：去掉多余小数位"""
    if isinstance(x, F):
        if x.denominator == 1:
            return str(x.numerator)
        return '%d/%d' % (x.numerator, x.denominator)
    s = ('%.2f' % x).rstrip('0').rstrip('.')
    return s


