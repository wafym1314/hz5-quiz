from fractions import Fraction as F


def num(x):
    if isinstance(x, F):
        if x.denominator == 1:
            return str(x.numerator)
        return '%d/%d' % (x.numerator, x.denominator)
    s = ('%.2f' % x).rstrip('0').rstrip('.')
    return s


def build(A):
    # ══════════ 六下·第3单元 图形的运动 ══════════
    A.U('6sx-10', '六下·第3单元 图形的运动')
    A.C('把一个图形平移后，图形的（　）。', '形状和大小不变，只是位置变了',
        ['形状变了', '大小变了', '形状和大小都变了'],
        '图形运动：平移不改变形状大小', '解析：平移只是把图形整体移动到别处，形状和大小都不变。')
    A.C('描述一次平移，要说清楚（　）。', '移动的方向和距离',
        ['只有方向', '只有距离', '图形的周长'],
        '图形运动：平移的两个要素', '解析：知道往哪个方向移、移多远，才能确定平移后的位置。')
    A.C('把一个图形旋转后，图形的（　）。', '形状和大小都不变',
        ['形状变大小不变', '大小变形状不变', '形状和大小都变'],
        '图形运动：旋转不改变形状大小', '解析：旋转只是把图形绕一个点转动，本身没有改变。')
    A.C('描述一次旋转，要说清楚（　）。', '旋转中心、方向和角度',
        ['只有角度', '只有方向', '只有旋转中心'],
        '图形运动：旋转的三要素', '解析：绕哪个点转、往哪边转、转多少度，三个都要说。')
    A.C('把图形对折后两边能完全重合，这个图形是（　）。', '轴对称图形',
        ['旋转图形', '平移图形', '不规则图形'],
        '图形运动：轴对称图形的含义', '解析：对折后完全重合的图形叫轴对称图形。')
    A.C('图形平移后，两组对应点连成的线段（　）。', '互相平行并且一样长',
        ['互相垂直', '一样长但相交', '长短不一'],
        '图形运动：平移后对应点连线的特点', '解析：平移是整体移动，每组对应点移动的路线都一样。')
    A.C('图形旋转后，每组对应点到旋转中心的距离（　）。', '相等',
        ['不相等', '一个变大一个变小', '无法确定'],
        '图形运动：旋转后对应点到中心的距离', '解析：旋转时图形上的点到中心的距离保持不变。')
    A.C('钟面上指针走动的方向与钟面指针运动方向相同的旋转叫（　）。', '顺时针旋转',
        ['逆时针旋转', '平移', '对称'],
        '图形运动：顺时针与逆时针', '解析：与钟表指针走向一致的是顺时针，相反的是逆时针。')
    A.C('正方形有（　）条对称轴。', '4', ['2', '3', '无数'],
        '图形运动：正方形的对称轴条数', '解析：两条对角线加两组对边中点的连线，共 4 条。')
    A.C('下面（　）是平移现象。', '电梯上下运行', ['钟面指针走动', '风车转动', '拧瓶盖'],
        '图形运动：生活中的平移现象', '解析：电梯整体沿直线移动，属于平移。')
    A.C('下面（　）是旋转现象。', '风车转动', ['推拉抽屉', '电梯上升', '滑滑梯'],
        '图形运动：生活中的旋转现象', '解析：风车绕中心轴转动，属于旋转。')
    A.C('一个图形旋转 90° 后，原来朝右的边变成朝（　）。', '下',
        ['仍朝右', '朝左', '朝上'],
        '图形运动：旋转 90° 后方向的变化', '解析：顺时针旋转 90°，朝右的边转到朝下。')
    A.C('把一个图形先向右平移 3 格，再向下平移 2 格，结果与（　）相同。',
        '先向下平移 2 格，再向右平移 3 格', ['只向右平移 5 格', '只向下平移 5 格', '无法平移'],
        '图形运动：两次平移可以交换顺序', '解析：平移的先后顺序不影响最终结果。')
    A.C('一个图形绕一点旋转 360° 后，它（　）。', '回到原来的位置',
        ['转到相反方向', '变大了一圈', '变成一个点'],
        '图形运动：旋转 360° 的结果', '解析：转一整圈后，图形回到原来的位置。')
    A.F('平移只改变图形的____，不改变形状和大小。', '位置',
        '图形运动：平移改变的是位置（填空）', '解析：平移只改变位置。')
    A.F('长方形有____条对称轴。', '2',
        '图形运动：长方形的对称轴条数（填空）', '解析：两组对边中点的连线，共 2 条。')
    A.H('一个点 A 绕点 O 顺时针旋转 90°，点 A 到点 O 的距离是 4 cm，旋转后 A 到 O 的距离（　）。',
        '还是 4 cm', ['变成 8 cm', '变成 2 cm', '变成 0'],
        '图形运动：旋转后到中心距离不变', '解析：旋转不改点到旋转中心的距离。')
    A.H('把一个三角形先平移再旋转，得到的图形与原图相比（　）。', '形状和大小都相同',
        ['形状相同大小不同', '形状不同大小相同', '无法确定'],
        '图形运动：平移与旋转的组合', '解析：平移和旋转都只改变位置，形状大小不变。')
    A.H('下面对称轴最多的是（　）。', '圆', ['正方形', '等边三角形', '长方形'],
        '图形运动：哪种图形对称轴最多', '解析：圆有无数条对称轴，比这些图形都多。')
    A.H('镜子里看到的钟表时刻与实际时刻（　）。', '左右相反',
        ['完全相同', '上下相反', '相差 12 小时'],
        '图形运动：镜面对称的特点', '解析：镜面对称相当于左右互换，所以看起来左右相反。')

