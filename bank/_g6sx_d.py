    A.U('6sx-11', '六下·第4单元 正比例与反比例')
    A.C('两种相关联的量，一种量变化另一种也随着变化，如果它们的（　）一定，就成正比例。',
        '比值', ['和', '差', '积'],
        '正反比例：正比例的意义', '解析：比值（商）一定的两种量成正比例。')
