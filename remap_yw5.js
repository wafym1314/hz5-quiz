function ser(q){
  const keys = Object.keys(q);
  return '{' + keys.map(k=>{
    const v = q[k];
    if (typeof v === 'string') return k + ':' + JSON.stringify(v);
    if (Array.isArray(v)) return k + ':' + JSON.stringify(v);
    return k + ':' + v;
  }).join(',') + '}';
}

let iCounter = 0;
const fiveUp = [];
for (const item of STRUCT) {
  const { num, name, src } = item;
  const ch = '五上·第' + num + '课 ' + name;
  const c = 'yw-' + num;
  if (src === 'new' || src === 'regen') {
    const arr = AUTH[num];
    if (!arr) throw new Error('缺少新题: ' + num);
    for (const [q,o,a,k,e] of arr) {
      fiveUp.push({ c, ch, f:0, q, o, a, k, e, i: iCounter++ });
    }
  } else {
    const old = byCode[src];
    if (!old) throw new Error('缺少旧题: ' + src);
    for (const q of old) {
      fiveUp.push({ c, ch, f:q.f, q:q.q, o:q.o, a:q.a, k:q.k, e:q.e, i: iCounter++ });
    }
  }
}

